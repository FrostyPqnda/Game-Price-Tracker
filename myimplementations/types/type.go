// Package types holds the data models and shared types used across the
// tracker: the documents stored in MongoDB, and the CLI command plumbing.
package types

import (
	"time"

	"go.mongodb.org/mongo-driver/v2/mongo"
)

// A PriceRecord stores a game's price data as it was at one point in time.
// It is used both for the current price (Game.PriceSnapshot) and for each
// entry in Game.PriceHistory.
type PriceRecord struct {
	OriginalPrice float64   `bson:"original_price" json:"original_price"` // Price without discount
	DiscountPrice float64   `bson:"discount_price" json:"discount_price"` // Price with discount
	Discount      int64     `bson:"discount" json:"discount"`             // Discount perceent (multiplied by 100)
	CheckedAt     time.Time `bson:"checked_at" json:"checked_at"`         // Last time the price was checked
}

// A Game represents the Steam game data stored for one app ID.
//
// PriceSnapshot is the most recent price. PriceHistory is a list of past
// prices, oldest first; entries are added only when a price changes, so it is
// a record of price changes and not of every check. The latest snapshot is
// normally also the last history entry.
type Game struct {
	AppId         int           `bson:"_id" json:"app_id"`                    // The unique app ID generated by steam
	Title         string        `bson:"title" json:"title"`                   // The game's title
	URL           string        `bson:"url" json:"url"`                       // The game's webpage
	PriceSnapshot PriceRecord   `bson:"price_snapshot" json:"price_snapshot"` // The game's price data currently
	PriceHistory  []PriceRecord `bson:"price_history" json:"price_history"`   // The game's price history over time
}

// App holds the shared dependencies that commands run against.
type App struct {
	Games   *mongo.Collection
	Watches *mongo.Collection
}

type Watch struct {
	UserId            string    `bson:"user_id"`
	ChannelId         string    `bson:"channel_id"`
	AppId             int       `bson:"app_id"`
	LastNotifiedPrice float64   `bson:"last_notified_price"`
	CreatedAt         time.Time `bson:"created_at"`
	IntervalAmount    int64     `bson:"interval_amount"`
	IntervalUnit      string    `bson:"interval_unit"` // minute, day, week, month
	NextCheckAt       time.Time `bson:"next_check_at"`
}
